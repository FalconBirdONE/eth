// Compiles src/*.sol with solc-js and writes out/SetupAttestations.json plus
// the ABI as TypeScript for the workflow.  bun compile.ts

import { mkdirSync, readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";
import solc from "solc";

const SRC = join(import.meta.dir, "src");
const OUT = join(import.meta.dir, "out");
const ABI_TS = join(import.meta.dir, "..", "setup-attestor", "abi.ts");

function collect(dir: string): Record<string, { content: string }> {
  const sources: Record<string, { content: string }> = {};
  for (const name of readdirSync(dir)) {
    const path = join(dir, name);
    if (statSync(path).isDirectory()) Object.assign(sources, collect(path));
    else if (name.endsWith(".sol")) sources[relative(SRC, path)] = { content: readFileSync(path, "utf8") };
  }
  return sources;
}

const input = {
  language: "Solidity",
  sources: collect(SRC),
  settings: {
    optimizer: { enabled: true, runs: 200 },
    evmVersion: "cancun",
    outputSelection: { "*": { "*": ["abi", "evm.bytecode.object"] } },
  },
};

const output = JSON.parse(solc.compile(JSON.stringify(input)));
const errors = (output.errors ?? []).filter((e: { severity: string }) => e.severity === "error");
for (const e of output.errors ?? []) console.error(e.formattedMessage);
if (errors.length) process.exit(1);

const contract = output.contracts["SetupAttestations.sol"].SetupAttestations;
mkdirSync(OUT, { recursive: true });
writeFileSync(
  join(OUT, "SetupAttestations.json"),
  JSON.stringify({ abi: contract.abi, bytecode: `0x${contract.evm.bytecode.object}` }, null, 2),
);
writeFileSync(
  ABI_TS,
  `// Generated by cre/contracts/compile.ts from SetupAttestations.sol. Do not edit.\n` +
    `export const SetupAttestationsABI = ${JSON.stringify(contract.abi, null, 2)} as const\n`,
);
console.log(`SetupAttestations compiled with solc ${solc.version()}`);
console.log(`  bytecode ${contract.evm.bytecode.object.length / 2} bytes -> out/SetupAttestations.json`);
console.log(`  ABI -> setup-attestor/abi.ts`);
